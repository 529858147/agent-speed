#!/usr/bin/env python3
"""Generate Sources/AgentSpeed/Localization/StringTable.swift from the shared and macOS string tables."""

import json
import re
import sys
from pathlib import Path

LANGUAGES = ("zh-Hant", "zh-Hans", "en", "ja")
SPECIFIER = re.compile(r"%(?:\d+\$)?[@dfs]|%%")

MACOS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = MACOS_DIR.parent
SHARED = REPO_ROOT / "spec" / "strings.json"
PLATFORM = MACOS_DIR / "Resources" / "strings.macos.json"
OUTPUT = MACOS_DIR / "Sources" / "AgentSpeed" / "Localization" / "StringTable.swift"


def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        data = json.load(handle)
    return {key: value for key, value in data.items() if not key.startswith("_")}


def swift_literal(text: str) -> str:
    escaped = (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def validate(key: str, entry: dict, origin: str, errors: list) -> None:
    if not isinstance(entry, dict):
        errors.append(f"{origin}: {key} is not an object")
        return
    missing = [lang for lang in LANGUAGES if not isinstance(entry.get(lang), str) or not entry[lang]]
    if missing:
        errors.append(f"{origin}: {key} is missing {', '.join(missing)}")
        return
    reference = sorted(SPECIFIER.findall(entry["en"]))
    for lang in LANGUAGES:
        if sorted(SPECIFIER.findall(entry[lang])) != reference:
            errors.append(f"{origin}: {key} [{lang}] format specifiers differ from en")


def main() -> int:
    shared = load(SHARED)
    platform = load(PLATFORM)
    errors: list = []
    for key, entry in shared.items():
        validate(key, entry, "spec/strings.json", errors)
    for key, entry in platform.items():
        validate(key, entry, "strings.macos.json", errors)
        if key in shared:
            errors.append(f"strings.macos.json: {key} duplicates a shared key")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    merged = {**shared, **platform}
    lines = [
        "// Generated by macos/scripts/sync-strings.py from spec/strings.json and",
        "// macos/Resources/strings.macos.json. Do not edit by hand.",
        "",
        "enum StringTable {",
        "    struct Entry: Sendable {",
        "        let zhHant: String",
        "        let zhHans: String",
        "        let en: String",
        "        let ja: String",
        "",
        "        init(_ zhHant: String, _ zhHans: String, _ en: String, _ ja: String) {",
        "            self.zhHant = zhHant",
        "            self.zhHans = zhHans",
        "            self.en = en",
        "            self.ja = ja",
        "        }",
        "    }",
        "",
        "    static let entries: [String: Entry] = [",
    ]
    for key in sorted(merged):
        entry = merged[key]
        values = ", ".join(swift_literal(entry[lang]) for lang in LANGUAGES)
        lines.append(f"        {swift_literal(key)}: Entry({values}),")
    lines += ["    ]", "}", ""]

    content = "\n".join(lines)
    if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == content:
        print(f"StringTable.swift is up to date ({len(merged)} keys)")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} ({len(merged)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
