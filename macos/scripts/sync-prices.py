#!/usr/bin/env python3
"""Embed spec/assets/prices.json and spec/assets/currencies.json (METRICS 9, DESIGN 9) into
Sources/AgentSpeedCore/Pricing/BundledPriceAssets.swift.

  python3 macos/scripts/sync-prices.py           # regenerate
  python3 macos/scripts/sync-prices.py --check   # exit 1 when the generated file is stale

The JSON files stay the single source of truth; the app parses the embedded copies at first use, so the universal
binary needs no resource bundle. `swift test` fails while an embedded copy differs from its spec file.
"""

import json
import sys
from pathlib import Path

MACOS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = MACOS_DIR.parent
SOURCES = {
    "prices": REPO_ROOT / "spec" / "assets" / "prices.json",
    "currencies": REPO_ROOT / "spec" / "assets" / "currencies.json",
}
OUTPUT = MACOS_DIR / "Sources" / "AgentSpeedCore" / "Pricing" / "BundledPriceAssets.swift"


def literal(name: str, text: str) -> str:
    json.loads(text)
    body = text[:-1] if text.endswith("\n") else text
    if '"""#' in body or "\\#" in body:
        raise SystemExit(f"{name}.json contains a sequence that cannot live in a raw Swift string")
    return (
        f"    /// spec/assets/{name}.json without its final newline.\n"
        f'    static let {name} = #"""\n'
        f"{body}\n"
        '"""#\n'
    )


def render() -> str:
    parts = [literal(name, path.read_text(encoding="utf-8")) for name, path in SOURCES.items()]
    return (
        "// Generated by macos/scripts/sync-prices.py from spec/assets/prices.json and spec/assets/currencies.json.\n"
        "// Do not edit by hand.\n"
        "\n"
        "enum BundledPriceAssets {\n" + "\n".join(parts) + "}\n"
    )


def main() -> int:
    generated = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if "--check" in sys.argv[1:]:
        if current != generated:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is stale; run macos/scripts/sync-prices.py", file=sys.stderr)
            return 1
        return 0
    if current != generated:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    else:
        print(f"{OUTPUT.relative_to(REPO_ROOT)} is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
