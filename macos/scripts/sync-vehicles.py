#!/usr/bin/env python3
"""Embed spec/assets/vehicles.json (DESIGN 4c) into Sources/AgentSpeedHero/Asset/HeroAssetJSON.swift.

  python3 macos/scripts/sync-vehicles.py           # regenerate
  python3 macos/scripts/sync-vehicles.py --check   # exit 1 when the generated file is stale

The JSON stays the single source of truth; the app parses the embedded copy once at first use, so the universal
binary needs no resource bundle. `swift test` fails while the embedded copy differs from the spec file.
"""

import json
import sys
from pathlib import Path

MACOS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = MACOS_DIR.parent
SOURCE = REPO_ROOT / "spec" / "assets" / "vehicles.json"
OUTPUT = MACOS_DIR / "Sources" / "AgentSpeedHero" / "Asset" / "HeroAssetJSON.swift"


def render(text: str) -> str:
    json.loads(text)
    body = text[:-1] if text.endswith("\n") else text
    if '"""#' in body or "\\#" in body:
        raise SystemExit("vehicles.json contains a sequence that cannot live in a raw Swift string")
    return (
        "// Generated by macos/scripts/sync-vehicles.py from spec/assets/vehicles.json. Do not edit by hand.\n"
        "\n"
        "enum HeroAssetJSON {\n"
        "    /// spec/assets/vehicles.json without its final newline.\n"
        '    static let text = #"""\n'
        f"{body}\n"
        '"""#\n'
        "}\n"
    )


def main() -> int:
    generated = render(SOURCE.read_text(encoding="utf-8"))
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if "--check" in sys.argv[1:]:
        if current != generated:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is stale; run macos/scripts/sync-vehicles.py", file=sys.stderr)
            return 1
        return 0
    if current != generated:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    else:
        print(f"{OUTPUT.relative_to(REPO_ROOT)} is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
